#!/usr/bin/env python3
"""
Konversi data/raw/master-stores.xlsx (sheet Stores) ke:
  1. data/clean/master-stores.csv - format ramah Supabase (empty -> NULL)
  2. sql/master-stores.sql - CREATE TABLE public.master_stores untuk Supabase/Postgres

Penggunaan (dari root proyek):
    python3 scripts/clean/clean_stores.py
    python3 scripts/clean/clean_stores.py <path_ke_file.xlsx> [sheet_name]
"""

import csv
import datetime
import sys
from collections import Counter
from pathlib import Path

from openpyxl import load_workbook

ROOT = Path(__file__).resolve().parents[2]
NULL_LITERAL = "NULL"  # ditulis tanpa quote di CSV, dibaca Postgres sebagai NULL


def normalize(cell):
    """Kembalikan string CSV untuk satu sel (semua kolom text)."""
    if cell is None:
        return NULL_LITERAL
    if isinstance(cell, bool):
        return str(cell)
    if isinstance(cell, datetime.datetime):
        if cell.time() == datetime.time(0, 0):
            return cell.date().isoformat()
        return cell.isoformat(sep=" ")
    if isinstance(cell, int):
        return str(cell)
    if isinstance(cell, float):
        if cell.is_integer():
            return str(int(cell))
        return repr(cell)
    text = str(cell).strip()
    if text == "":
        return NULL_LITERAL
    return text


def main():
    default_src = ROOT / "data" / "raw" / "master-stores.xlsx"
    src = Path(sys.argv[1]) if len(sys.argv) > 1 else default_src
    if not src.is_absolute() and not src.exists():
        candidate = ROOT / "data" / "raw" / src.name
        if candidate.exists():
            src = candidate
    sheet_name = sys.argv[2] if len(sys.argv) > 2 else "Stores"

    if not src.exists():
        sys.exit(f"File tidak ditemukan: {src}")

    wb = load_workbook(src, data_only=True, read_only=True)
    if sheet_name not in wb.sheetnames:
        sys.exit(f"Sheet '{sheet_name}' tidak ada. Sheets: {wb.sheetnames}")
    ws = wb[sheet_name]

    rows_iter = ws.iter_rows(values_only=True)
    header = [str(h).strip() if h is not None else "" for h in next(rows_iter)]

    out_csv = ROOT / "data" / "clean" / (src.stem + ".csv")
    out_sql = ROOT / "sql" / (src.stem + ".sql")

    null_counts = {col: 0 for col in header}
    total = 0
    store_codes = []

    with open(out_csv, "w", newline="", encoding="utf-8") as fh:
        writer = csv.writer(fh, quoting=csv.QUOTE_MINIMAL, lineterminator="\n")
        writer.writerow(header)
        for row in rows_iter:
            if all(v is None for v in row):
                continue
            total += 1
            out_row = []
            for col, cell in zip(header, row):
                value = normalize(cell)
                if value == NULL_LITERAL:
                    null_counts[col] += 1
                out_row.append(value)
                if col == "store_code" and value != NULL_LITERAL:
                    store_codes.append(value.strip())
            writer.writerow(out_row)

    dups = sorted(k for k, v in Counter(store_codes).items() if v > 1)

    table = "master_stores"
    col_defs = []
    for col in header:
        if col == "store_code":
            col_defs.append(f'    "{col}" text primary key')
        else:
            col_defs.append(f'    "{col}" text')
    columns_sql = ",\n".join(col_defs)
    total_nulls = sum(null_counts.values())

    sql = f"""-- Generated by clean_stores.py dari {src.name}
-- Data: {total} baris, {total_nulls} NULL total
-- Import CSV: Supabase Table Editor -> Table -> Import data from CSV
-- Atau psql:
--   \\copy "{table}" from '{out_csv.name}' with (format csv, header true, null 'NULL');

create table if not exists public."{table}" (
{columns_sql}
);
"""
    out_sql.write_text(sql, encoding="utf-8")

    print(f"XLSX : {src} (sheet '{sheet_name}')")
    print(f"Rows : {total}")
    print(f"CSV  : {out_csv}")
    print(f"SQL  : {out_sql}  -> public.\"{table}\"")
    cols_with_null = [c for c in header if null_counts[c]]
    if cols_with_null:
        print("NULL per kolom:")
        for c in cols_with_null:
            print(f"  - {c}: {null_counts[c]}")
    else:
        print("NULL per kolom: tidak ada")
    if dups:
        print(f"DUPLIKAT store_code ({len(dups)}): {dups[:10]}")
    else:
        print("Duplikat store_code: tidak ada")


if __name__ == "__main__":
    main()
