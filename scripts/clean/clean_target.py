#!/usr/bin/env python3
"""
Konversi data/raw/master-target.xlsx (sheet Target) ke:
  1. data/clean/master-target.csv - format ramah Supabase (empty -> NULL, target dibulatkan ke integer)
  2. sql/master-target.sql  - CREATE TABLE public.master_target untuk Supabase/Postgres

Penggunaan (dari root proyek):
    python3 scripts/clean/clean_target.py
    python3 scripts/clean/clean_target.py <path_ke_file.xlsx> [sheet_name]
"""

import csv
import datetime
import sys
from decimal import Decimal, ROUND_HALF_UP
from pathlib import Path

from openpyxl import load_workbook

ROOT = Path(__file__).resolve().parents[2]
NULL_LITERAL = "NULL"  # ditulis tanpa quote di CSV, dibaca Postgres sebagai NULL

# Kolom target: dibulatkan ke rupiah penuh (integer)
TARGET_COLUMNS = {
    "total_target", "apple_target", "android_target", "samsung_target",
    "xiaomi_target", "huawei_target", "motorola_target", "oppo_target",
    "infinix_target", "accessories_target", "vas_target",
}


def round_int(value) -> str:
    """Bulatkan numerik ke integer (ROUND_HALF_UP), kembalikan string."""
    d = Decimal(str(value)).quantize(Decimal("1"), rounding=ROUND_HALF_UP)
    return str(int(d))


def normalize(col, cell):
    """Kembalikan string CSV untuk satu sel."""
    if cell is None:
        return NULL_LITERAL
    if isinstance(cell, bool):
        return str(cell)
    if isinstance(cell, datetime.datetime):
        if cell.time() == datetime.time(0, 0):
            return cell.date().isoformat()
        return cell.isoformat(sep=" ")
    if col in TARGET_COLUMNS:
        if isinstance(cell, (int, float, Decimal)):
            return round_int(cell)
        text = str(cell).strip().replace(",", "")
        if text == "":
            return NULL_LITERAL
        try:
            return round_int(text)
        except Exception:
            return text
    if isinstance(cell, int):
        return str(cell)
    if isinstance(cell, float):
        if cell.is_integer():
            return str(int(cell))
        return repr(cell)
    text = str(cell).strip()
    if text == "":
        return NULL_LITERAL
    return text


def main():
    default_src = ROOT / "data" / "raw" / "master-target.xlsx"
    src = Path(sys.argv[1]) if len(sys.argv) > 1 else default_src
    if not src.is_absolute() and not src.exists():
        candidate = ROOT / "data" / "raw" / src.name
        if candidate.exists():
            src = candidate
    sheet_name = sys.argv[2] if len(sys.argv) > 2 else "Target"

    if not src.exists():
        sys.exit(f"File tidak ditemukan: {src}")

    wb = load_workbook(src, data_only=True, read_only=True)
    if sheet_name not in wb.sheetnames:
        sys.exit(f"Sheet '{sheet_name}' tidak ada. Sheets: {wb.sheetnames}")
    ws = wb[sheet_name]

    rows_iter = ws.iter_rows(values_only=True)
    header = [str(h).strip() if h is not None else "" for h in next(rows_iter)]

    out_csv = ROOT / "data" / "clean" / (src.stem + ".csv")
    out_sql = ROOT / "sql" / (src.stem + ".sql")

    null_counts = {col: 0 for col in header}
    total = 0

    with open(out_csv, "w", newline="", encoding="utf-8") as fh:
        writer = csv.writer(fh, quoting=csv.QUOTE_MINIMAL, lineterminator="\n")
        writer.writerow(header)
        for row in rows_iter:
            if all(v is None for v in row):
                continue
            total += 1
            out_row = []
            for col, cell in zip(header, row):
                value = normalize(col, cell)
                if value == NULL_LITERAL:
                    null_counts[col] += 1
                out_row.append(value)
            writer.writerow(out_row)

    table = "master_target"
    col_defs = []
    for col in header:
        if col == "store_code":
            col_defs.append(f'    "{col}" text primary key')
        elif col == "store_name":
            col_defs.append(f'    "{col}" text')
        else:
            col_defs.append(f'    "{col}" bigint')
    columns_sql = ",\n".join(col_defs)
    total_nulls = sum(null_counts.values())

    sql = f"""-- Generated by clean_target.py dari {src.name}
-- Data: {total} baris, {total_nulls} NULL total
-- Kolom *_target dibulatkan ke integer (ROUND_HALF_UP)
-- Import CSV: Supabase Table Editor -> Table -> Import data from CSV
-- Atau psql:
--   \\copy "{table}" from '{out_csv.name}' with (format csv, header true, null 'NULL');

create table if not exists public."{table}" (
{columns_sql}
);
"""
    out_sql.write_text(sql, encoding="utf-8")

    print(f"XLSX : {src} (sheet '{sheet_name}')")
    print(f"Rows : {total}")
    print(f"CSV  : {out_csv}")
    print(f"SQL  : {out_sql}  -> public.\"{table}\"")
    cols_with_null = [c for c in header if null_counts[c]]
    if cols_with_null:
        print("NULL per kolom:")
        for c in cols_with_null:
            print(f"  - {c}: {null_counts[c]}")
    else:
        print("NULL per kolom: tidak ada")


if __name__ == "__main__":
    main()
