#!/usr/bin/env python3
"""
Konversi store-transactions.xlsx (sheet RAW) ke:
  1. store-transactions.csv   - format ramah Supabase (empty -> NULL)
  2. store-transactions.sql   - CREATE TABLE untuk Supabase/Postgres

Penggunaan (dari root proyek):
    python3 scripts/convert_xlsx_to_csv.py
    python3 scripts/convert_xlsx_to_csv.py <path_ke_file.xlsx> [sheet_name]

Default input: data/store-transactions.xlsx
Output: data/*.csv + sql/*.sql
"""

import csv
import datetime
import re
import sys
from pathlib import Path

from openpyxl import load_workbook

ROOT = Path(__file__).resolve().parents[1]

NULL_LITERAL = "NULL"  # ditulis tanpa quote di CSV, dibaca Postgres sebagai NULL


def normalize(cell):
    """Kembalikan (nilai_string, jenis_inferensi) untuk satu sel."""
    if cell is None:
        return NULL_LITERAL, None
    if isinstance(cell, datetime.datetime):
        if cell.time() == datetime.time(0, 0):
            return cell.date().isoformat(), "date"
        return cell.isoformat(sep=" "), "timestamp"
    if isinstance(cell, bool):
        return str(cell), "boolean"
    if isinstance(cell, int):
        return str(cell), "integer"
    if isinstance(cell, float):
        if cell.is_integer():
            return str(int(cell)), "integer"
        return repr(cell), "numeric"
    text = str(cell).strip()
    if text == "":
        return NULL_LITERAL, None  # string kosong -> NULL
    if text.upper() == NULL_LITERAL:
        # hindari ambigu: kutip agar bukan NULL palsu
        return text, "text"
    return text, "text"


def infer_sql_type(current, incoming):
    """Gabungkan jenis inferensi dari banyak baris jadi satu tipe SQL."""
    if incoming is None:
        return current
    if current is None:
        return incoming
    if current == incoming:
        return current
    if {current, incoming} == {"integer", "numeric"}:
        return "numeric"
    # campur tanggal dan teks dll -> paksa text (biarkan Supabase menampung apa adanya)
    return "text"


def main():
    default_src = ROOT / "data" / "store-transactions.xlsx"
    src = Path(sys.argv[1]) if len(sys.argv) > 1 else default_src
    if not src.is_absolute() and not src.exists():
        # izinkan argumen berupa nama file saja -> cari di data/
        candidate = ROOT / "data" / src.name
        if candidate.exists():
            src = candidate
    sheet_name = sys.argv[2] if len(sys.argv) > 2 else "RAW"

    if not src.exists():
        sys.exit(f"File tidak ditemukan: {src}")

    wb = load_workbook(src, data_only=True, read_only=True)
    ws = wb[sheet_name]

    rows_iter = ws.iter_rows(values_only=True)
    header = [str(h).strip() if h is not None else "" for h in next(rows_iter)]

    out_csv = ROOT / "data" / (src.stem + ".csv")
    out_sql = ROOT / "sql" / (src.stem + ".sql")

    sql_types = {col: None for col in header}
    null_counts = {col: 0 for col in header}
    total = 0

    # ---- tulis CSV ----
    with open(out_csv, "w", newline="", encoding="utf-8") as fh:
        writer = csv.writer(fh, quoting=csv.QUOTE_MINIMAL, lineterminator="\n")
        writer.writerow(header)
        for row in rows_iter:
            if all(v is None for v in row):
                continue  # lewati baris kosong total
            total += 1
            out_row = []
            for col, cell in zip(header, row):
                value, kind = normalize(cell)
                if value == NULL_LITERAL and kind is None:
                    null_counts[col] += 1
                elif value == NULL_LITERAL:
                    # teks literal "NULL" asli -> kutip agar tidak jadi NULL
                    value = '"NULL"'
                    sql_types[col] = infer_sql_type(sql_types[col], "text")
                else:
                    sql_types[col] = infer_sql_type(sql_types[col], kind)
                out_row.append(value)
            writer.writerow(out_row)

    # ---- tulis SQL CREATE TABLE ----
    table = re.sub(r"[^a-z0-9_]+", "_", src.stem.lower()).strip("_")
    col_defs = []
    for col in header:
        t = sql_types[col] or "text"
        sql_t = {"integer": "integer", "numeric": "numeric",
                 "date": "date", "timestamp": "timestamp",
                 "boolean": "boolean"}.get(t, "text")
        col_defs.append(f'    "{col}" {sql_t}')

    columns_sql = ",\n".join(col_defs)
    total_nulls = sum(null_counts.values())

    sql = f"""-- Generated by convert_xlsx_to_csv.py dari {src.name}
-- Data: {total} baris, {total_nulls} NULL total
-- Import CSV: Supabase Table Editor -> Table -> Import data from CSV
-- Atau psql:
--   \\copy "{table}" from '{out_csv.name}' with (format csv, header true, null 'NULL');

create table if not exists public."{table}" (
{columns_sql}
);
"""

    out_sql.write_text(sql, encoding="utf-8")

    # ---- laporan ----
    print(f"XLSX : {src} (sheet '{sheet_name}')")
    print(f"Rows : {total}")
    print(f"CSV  : {out_csv}")
    print(f"SQL  : {out_sql}  -> public.\"{table}\"")
    cols_with_null = [c for c in header if null_counts[c]]
    if cols_with_null:
        print("NULL per kolom:")
        for c in cols_with_null:
            print(f"  - {c}: {null_counts[c]}")
    else:
        print("NULL per kolom: tidak ada")


if __name__ == "__main__":
    main()
